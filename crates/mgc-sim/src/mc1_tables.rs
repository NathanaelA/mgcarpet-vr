//! MC1's texture corner-class machinery, shared between the terrain
//! generator (`mgc-import::mc1_terrain`, texture-selection pass) and
//! the load-time feature pass ([`crate::features`], terrain repaints
//! after digging).
//!
//! Reference: remc1 `sub_32560` (sub_main.cpp:39947): candidate buckets
//! keyed by base-7 quad corner code over all 8 dihedral arrangements,
//! plus the flat first-candidate fallback table `byte_B5D40` the engine
//! uses to retile deformed terrain.

/// Candidate textures for one quad corner-class key.
#[derive(Clone, Copy)]
pub struct Bucket {
    pub count: u8,
    pub tex: [u8; 12],
    pub orient: [u8; 12],
}

/// The 8 dihedral placements of a texture's corner classes, in the
/// engine's insertion order, with their orientation codes (bit4 =
/// flip x, bit5 = flip y, bit6 = swap axes — the renderer's UV decode).
pub fn arrangements(corners: [u8; 4]) -> [([u8; 4], u8); 8] {
    let [a, b, c, d] = corners;
    [
        ([a, b, c, d], 0x00),
        ([b, a, d, c], 0x10),
        ([c, d, a, b], 0x30),
        ([d, c, b, a], 0x20),
        ([b, c, d, a], 0x60),
        ([c, b, a, d], 0x70),
        ([d, a, b, c], 0x50),
        ([a, d, c, b], 0x40),
    ]
}

/// Build the 7^4 candidate buckets (engine: the first phase of
/// `sub_32560`). Key = `343*NW + 49*NE + 7*SE + SW`.
pub fn corner_buckets() -> Vec<Bucket> {
    let mut buckets = vec![
        Bucket {
            count: 0,
            tex: [0; 12],
            orient: [0; 12],
        };
        7 * 7 * 7 * 7
    ];
    for (t, corners) in CORNER_CLASSES.iter().enumerate() {
        if corners.contains(&0xFF) {
            continue;
        }
        for (p, orient) in arrangements(*corners) {
            let key = 343 * p[0] as usize + 49 * p[1] as usize + 7 * p[2] as usize + p[3] as usize;
            let bkt = &mut buckets[key];
            if (bkt.count as usize) < 12 {
                bkt.tex[bkt.count as usize] = t as u8;
                bkt.orient[bkt.count as usize] = orient;
                bkt.count += 1;
            }
        }
    }
    buckets
}

/// The engine's flat retile table (`byte_B5D40`, 2401 x {texture,
/// orientation-bits}): the first candidate of each bucket, or
/// `(1, 0)` where the bucket is empty. Used by the feature pass to
/// repaint terrain after height edits.
pub fn retile_table() -> Vec<[u8; 2]> {
    corner_buckets()
        .iter()
        .map(|b| {
            if b.count != 0 {
                [b.tex[0], b.orient[0]]
            } else {
                [1, 0]
            }
        })
        .collect()
}

